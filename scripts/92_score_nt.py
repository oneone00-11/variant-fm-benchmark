"""Milestone 8b / 11 — Nucleotide Transformer (NT) variant scoring.

ARCHIVAL RECONSTRUCTION OF THE NT SCORING PROCEDURE.
=====================================================
The original NT scoring was run once on a cloud GPU (single card); that ad-hoc
script and its environment were not committed, so NT — unlike every other model —
was not reproducible from this repository. This file restores the procedure so the
`nucleotide_transformer` column can be regenerated by anyone with a GPU.

This file documents the procedure; it is not the original script and contains no
scores. The committed NT values were produced by the original cloud-GPU run and
live in the (git-ignored) cache `nt_cache2.tsv`, already merged into
`data/processed/score_matrix_final.tsv`. Re-running this script on a GPU
regenerates that cache, but not byte-identically -- see the reproducibility-scope
table in README.md.

Model & scoring (per docs/milestone8b_results.md and the project record)
------------------------------------------------------------------------
- Checkpoint : InstaDeepAI/nucleotide-transformer-v2-500m-multi-species
  (non-overlapping 6-mer tokenizer, masked-language-model head).
- Score      : masked-token log-likelihood ratio at the variant position.
  The 6-mer token overlapping the variant is replaced by [MASK]; the model's
  log-probabilities at that position are read; the score is
      nt_score = log P(REF 6-mer | masked context) − log P(ALT 6-mer | masked context)
  so that HIGHER = the alternate allele is more disfavoured = MORE pathogenic
  (verified: splice P/LP mean ≈ +2.9 vs B/LB ≈ +0.5; orientation +1 in
  scripts/phase3_lib.py).
- Reference  : Ensembl GRCh38 release-112 (same assembly/annotation as SpliceAI/
  Pangolin, see docs/milestone6). The reference FASTA is git-ignored (refs/, large);
  see README "Data acquisition".

CONTEXT WINDOW — TO BE CONFIRMED
--------------------------------
The exact input context window used in the original cloud run was NOT recorded and
cannot be recovered from the cache (which stores only key + score). `WINDOW_BP`
below is a documented, reproducible DEFAULT that sits well within NT v2's native
context (2048 6-mer tokens ≈ 12 kb); it is NOT asserted to be the original value.
Confirm/replace it with the value actually used before claiming bit-exact
reproduction; see the reproducibility-scope table in README.md. Changing the window changes the
masked context and therefore the scores slightly.

Requirements (GPU environment; NOT in requirements.txt — analysis is CPU-only)
------------------------------------------------------------------------------
    pip install torch transformers pyfaidx pandas tqdm   # CUDA build of torch
Output: regenerates `nt_cache2.tsv` (key = chrom:pos:ref:alt, nt_score), the same
git-ignored cache the matrix is built from. Resumable (skips cached keys).

Usage:
    python scripts/92_score_nt.py                       # uses refs/grch38_subset.fa
    python scripts/92_score_nt.py /path/to/GRCh38.fa    # custom reference FASTA
"""
import sys
from pathlib import Path

import pandas as pd
from tqdm import tqdm

# --- Repo-relative paths (portable) -----------------------------------------
ROOT = Path(__file__).resolve().parents[1]
AR = ROOT / "data" / "processed" / "analysis_ready_v2.tsv"   # variants to score
# Reference FASTA: the Ensembl release-112 subset used throughout (git-ignored).
REF_FASTA = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "refs" / "grch38_subset.fa"
CACHE = ROOT / "nt_cache2.tsv"        # regenerates the existing (git-ignored) cache

CHECKPOINT = "InstaDeepAI/nucleotide-transformer-v2-500m-multi-species"
KMER = 6                # NT v2 uses non-overlapping 6-mer tokenization
WINDOW_BP = 6000        # DEFAULT context window (bp) centred on the variant.
                        # ~1000 tokens, << NT v2's 2048-token max. SEE HEADER:
                        # the original run's window is unconfirmed.
BASES = set("ACGT")


def load_model():
    """Load NT tokenizer + masked-LM head onto GPU if available."""
    import torch
    from transformers import AutoModelForMaskedLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(CHECKPOINT)
    model = AutoModelForMaskedLM.from_pretrained(CHECKPOINT)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model.to(device).eval()
    return tok, model, device


def masked_llr(tok, model, device, chrom_seq, pos0, ref, alt):
    """Masked-token LLR for one SNV. `chrom_seq` is the chromosome sequence
    (str, 0-based), `pos0` the 0-based variant index. Returns
    log P(ref 6-mer) − log P(alt 6-mer) at the masked variant token.
    Higher = more pathogenic. Returns None if out of bounds / non-ACGT."""
    import torch

    # Sanity: the reference base must match the FASTA (verifies coords/assembly).
    if chrom_seq[pos0].upper() != ref.upper():
        return None
    half = WINDOW_BP // 2
    start = max(0, pos0 - half)
    end = min(len(chrom_seq), pos0 + half)
    # Align the window start to the 6-mer frame so the variant sits inside one token.
    var_off = pos0 - start
    frame = var_off % KMER
    start += frame                       # shift so var_off is a multiple of KMER
    var_off = pos0 - start
    window = chrom_seq[start:end].upper()
    if set(window) - BASES:              # skip windows with N / ambiguity
        return None

    tok_idx = var_off // KMER            # index of the 6-mer token holding the variant
    within = var_off % KMER
    ref_kmer = window[tok_idx * KMER:(tok_idx + 1) * KMER]
    if len(ref_kmer) < KMER or ref_kmer[within] != ref.upper():
        return None
    alt_kmer = ref_kmer[:within] + alt.upper() + ref_kmer[within + 1:]

    # Tokenize the windowed sequence; mask the variant's 6-mer token; read logits.
    enc = tok(window, return_tensors="pt")
    input_ids = enc["input_ids"].to(device)
    # +1 offset for the leading CLS token NT prepends.
    mask_token_pos = tok_idx + 1
    ref_id = tok.convert_tokens_to_ids(ref_kmer)
    alt_id = tok.convert_tokens_to_ids(alt_kmer)
    if tok.unk_token_id in (ref_id, alt_id):
        return None
    input_ids[0, mask_token_pos] = tok.mask_token_id
    with torch.no_grad():
        logits = model(input_ids=input_ids).logits[0, mask_token_pos]
        logp = torch.log_softmax(logits, dim=-1)
    return float(logp[ref_id] - logp[alt_id])


def main():
    if not REF_FASTA.exists():
        sys.exit(f"Reference FASTA not found: {REF_FASTA}\n"
                 "Provide the Ensembl GRCh38 release-112 reference (see README).")
    from pyfaidx import Fasta

    variants = pd.read_csv(AR, sep="\t", dtype={"chrom": str}, low_memory=False)
    variants = variants[["chrom", "pos", "ref", "alt"]].drop_duplicates()

    done = {}
    if CACHE.exists():
        prev = pd.read_csv(CACHE, sep="\t")
        done = dict(zip(prev["key"], prev["nt_score"]))
    fasta = Fasta(str(REF_FASTA))
    tok, model, device = load_model()

    rows = []
    for r in tqdm(variants.itertuples(index=False), total=len(variants)):
        key = f"{r.chrom}:{r.pos}:{r.ref}:{r.alt}"
        if key in done:
            rows.append((key, done[key]))
            continue
        try:
            seq = str(fasta[r.chrom])               # chromosome sequence, 0-based
            score = masked_llr(tok, model, device, seq, int(r.pos) - 1, r.ref, r.alt)
        except Exception:
            score = None
        rows.append((key, "" if score is None else score))

    out = pd.DataFrame(rows, columns=["key", "nt_score"])
    out.to_csv(CACHE, sep="\t", index=False)
    n_ok = (out["nt_score"] != "").sum()
    print(f"NT scored {n_ok}/{len(out)} -> {CACHE}")
    print("Merge into the matrix on key=chrom:pos:ref:alt (column "
          "'nucleotide_transformer'); cache is git-ignored and regenerable by this script.")


if __name__ == "__main__":
    main()
